"""
Event System for Backtesting Engine

Implements event-driven architecture for clean separation of concerns.
Events flow through the system in a decoupled manner.

Event Types:
    - MARKET_DATA: New candle data available
    - SIGNAL: Trading signal generated
    - ORDER: Order placed
    - FILL: Order filled
    - POSITION_UPDATE: Position state changed
    - RISK_CHECK: Risk check result
"""

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum, auto
from typing import Optional, Dict, Any, List
import pandas as pd


class EventType(Enum):
    """Types of events in the backtest system."""
    MARKET_DATA = auto()      # New candle available
    SIGNAL = auto()           # Strategy generated signal
    ORDER = auto()            # Order to be executed
    FILL = auto()             # Order was filled
    POSITION_UPDATE = auto()  # Position state changed
    RISK_CHECK = auto()       # Risk check performed
    EXIT_SIGNAL = auto()      # Exit signal (SL/Target/Time)
    DAY_END = auto()          # End of trading day


@dataclass
class Event:
    """Base event class."""
    event_type: EventType
    timestamp: datetime
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class MarketDataEvent(Event):
    """
    New market data available.
    
    Triggered for each candle in the backtest.
    """
    event_type: EventType = EventType.MARKET_DATA
    timestamp: datetime = None
    symbol: str = ""
    open: float = 0.0
    high: float = 0.0
    low: float = 0.0
    close: float = 0.0
    volume: int = 0
    
    # Pre-computed features (added by FeatureEngine)
    vwap: Optional[float] = None
    ema_20: Optional[float] = None
    ema_50: Optional[float] = None
    rsi: Optional[float] = None
    atr: Optional[float] = None
    volume_factor: Optional[float] = None
    pct_change: Optional[float] = None
    intraday_return: Optional[float] = None
    
    # Full historical context if needed
    historical_df: Optional[pd.DataFrame] = None


@dataclass 
class SignalEvent(Event):
    """
    Trading signal generated by a strategy.
    """
    event_type: EventType = EventType.SIGNAL
    timestamp: datetime = None
    symbol: str = ""
    instrument_token: int = 0
    signal_type: str = "BUY"  # BUY or SELL
    strategy_id: str = ""
    price: float = 0.0
    stop_loss: float = 0.0
    target: float = 0.0
    quantity: Optional[int] = None
    reason: str = ""
    confidence: float = 1.0
    features: Dict[str, float] = field(default_factory=dict)


@dataclass
class OrderEvent(Event):
    """
    Order to be executed.
    
    Created by RiskEngine after signal passes checks.
    """
    event_type: EventType = EventType.ORDER
    timestamp: datetime = None
    symbol: str = ""
    instrument_token: int = 0
    order_type: str = "MARKET"  # MARKET, LIMIT
    side: str = "BUY"           # BUY or SELL
    quantity: int = 0
    price: float = 0.0          # For LIMIT orders
    stop_loss: float = 0.0
    target: float = 0.0
    strategy_id: str = ""
    signal_id: Optional[str] = None


@dataclass
class FillEvent(Event):
    """
    Order was filled.
    
    Generated by OrderSimulator after execution.
    """
    event_type: EventType = EventType.FILL
    timestamp: datetime = None
    symbol: str = ""
    instrument_token: int = 0
    side: str = "BUY"
    quantity: int = 0
    fill_price: float = 0.0
    commission: float = 0.0
    slippage: float = 0.0
    strategy_id: str = ""
    order_id: Optional[str] = None


@dataclass
class ExitSignalEvent(Event):
    """
    Exit signal for an open position.
    """
    event_type: EventType = EventType.EXIT_SIGNAL
    timestamp: datetime = None
    symbol: str = ""
    exit_reason: str = ""       # SL_HIT, TARGET_HIT, TRAILING_SL, TIME_EXIT
    exit_price: float = 0.0
    position_id: Optional[str] = None


@dataclass
class PositionUpdateEvent(Event):
    """
    Position state changed.
    """
    event_type: EventType = EventType.POSITION_UPDATE
    timestamp: datetime = None
    symbol: str = ""
    entry_price: float = 0.0
    current_price: float = 0.0
    quantity: int = 0
    unrealized_pnl: float = 0.0
    unrealized_pnl_pct: float = 0.0
    stop_loss: float = 0.0
    status: str = "OPEN"        # OPEN, CLOSED


@dataclass
class RiskCheckEvent(Event):
    """
    Result of risk check.
    """
    event_type: EventType = EventType.RISK_CHECK
    timestamp: datetime = None
    symbol: str = ""
    passed: bool = False
    reason: str = ""
    allowed_quantity: int = 0
    allocated_capital: float = 0.0


class EventQueue:
    """
    Simple event queue for processing events in order.
    """
    
    def __init__(self):
        self._events: List[Event] = []
    
    def push(self, event: Event) -> None:
        """Add event to queue."""
        self._events.append(event)
    
    def pop(self) -> Optional[Event]:
        """Remove and return next event."""
        if self._events:
            return self._events.pop(0)
        return None
    
    def is_empty(self) -> bool:
        """Check if queue is empty."""
        return len(self._events) == 0
    
    def clear(self) -> None:
        """Clear all events."""
        self._events.clear()
    
    def __len__(self) -> int:
        return len(self._events)
