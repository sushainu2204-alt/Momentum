"""
Signal Model

Trading signal generated by strategies.
"""
from typing import Optional, Dict, Any
from dataclasses import dataclass, asdict, field
from datetime import datetime
import json

from .enums import SignalType


@dataclass
class Signal:
    """
    Trading signal generated by a strategy.
    
    Represents a buy/sell recommendation with entry price,
    stop loss, and target levels.
    
    Attributes:
        symbol: Stock trading symbol (e.g., 'RELIANCE')
        instrument_token: Kite instrument token for API calls
        signal_type: BUY or SELL
        price: Entry price when signal was generated
        timestamp: When signal was generated
        reason: Human-readable reason for the signal
        quantity: Number of shares to trade
        stop_loss: Stop loss price
        target: Target price
        metadata: Additional strategy-specific data
    """
    symbol: str
    instrument_token: int
    signal_type: SignalType
    price: float
    timestamp: datetime
    reason: Optional[str] = None
    quantity: Optional[int] = None
    stop_loss: Optional[float] = None
    target: Optional[float] = None
    metadata: Optional[Dict[str, Any]] = field(default_factory=dict)
    
    def to_json(self) -> str:
        """
        Serialize signal to JSON string for Redis publishing.
        
        Returns:
            JSON string representation of the signal
        """
        data = {
            "symbol": self.symbol,
            "instrument_token": self.instrument_token,
            "signal_type": self.signal_type.value if isinstance(self.signal_type, SignalType) else self.signal_type,
            "price": self.price,
            "timestamp": self.timestamp.isoformat(),
            "reason": self.reason,
            "quantity": self.quantity,
            "stop_loss": self.stop_loss,
            "target": self.target,
            "metadata": self.metadata or {}
        }
        return json.dumps(data)
    
    @classmethod
    def from_json(cls, json_str: str) -> "Signal":
        """
        Deserialize signal from JSON string.
        
        Args:
            json_str: JSON string representation
            
        Returns:
            Signal instance
        """
        data = json.loads(json_str)
        data['timestamp'] = datetime.fromisoformat(data['timestamp'])
        data['signal_type'] = SignalType(data['signal_type'])
        return cls(**data)
    
    def to_dict(self) -> Dict[str, Any]:
        """
        Convert to dictionary.
        
        Returns:
            Dictionary representation
        """
        return asdict(self)
